def _norm_head(text: str) -> str:
    """تطبيع عنوان للمقارنة: بلا ## ولا تشكيل ولا همزات ولا علامات، ومسافات مفردة."""
    t = str(text or "").strip()
    t = re.sub(r"^#+\s*", "", t)
    t = re.sub(r"[\u064B-\u0652\u0670\u0640]", "", t)          # تشكيل وتطويل
    t = t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    t = t.replace("ة", "ه").replace("ى", "ي").replace("ئ", "ي").replace("ؤ", "و")
    t = re.sub(r"[^\u0621-\u064A0-9a-zA-Z ]+", " ", t)
    t = re.sub(r"\s+", " ", t).strip().lower()
    return t


_GENERIC = {_norm_head(h) for h in GENERIC_HEADINGS}


def is_generic_heading(heading: str) -> bool:
    h = _norm_head(heading)
    if h in _GENERIC:
        return True
    for g in _GENERIC:
        if g and (h.startswith(g + " ") or h.endswith(" " + g)):
            return True
    return False


